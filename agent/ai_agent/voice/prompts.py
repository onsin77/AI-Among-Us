"""语音会议提示词:按发言位次分思考强度(报警人极低 → 靠后渐强 → 表决最深)。

位次规则(用户要求):
- 第 0 位(报警人,第一个发言):极低思考强度,立刻开口,以说明自己的所作所为为主;
  坏人注意不要暴露对自己不利的信息。
- 非报警人:先听别人发言;轮到自己立刻开始。对"前一个发言者"思考不全是正常现象。
- 靠后位次信息更全:总结矛盾、明确指认。
- 全部发言结束后表决:最怀疑的人。
"""

